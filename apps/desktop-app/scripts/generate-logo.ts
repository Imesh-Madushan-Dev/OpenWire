/**
 * Writes the OpenWire logo: an open "O" with a wire leaving through the gap.
 *
 * SVG has no conic gradient, so the ring's colour sweep is built from short
 * arc segments, each a step further along the spectrum. Two variants:
 *
 *   dark  - midnight tile, white node. The static app icon, and the live
 *           window/tray icon while the app is in dark mode.
 *   light - glass tile. The live icon and in-app mark in light mode.
 *
 * Regenerate after editing (from apps/desktop-app):
 *   bun scripts/generate-logo.ts
 *   bunx tauri icon src-tauri/app-icon.svg            (then delete icons/android, icons/ios)
 *   bunx tauri icon src-tauri/app-icon-light.svg -o src-tauri/icons/light --png 256
 */

import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dir, '..')

type Rgb = [number, number, number]

const SPECTRUM = ['#ffd60a', '#ff8a00', '#ff2e63', '#c026d3', '#7c3aed', '#2f6bff', '#00d4ff']

interface Variant {
  tile: [string, string]
  wire: [string, string]
  node: string
  glow: number
}

const VARIANTS = {
  dark: { tile: ['#2a1f5c', '#0d0a1f'], wire: ['#ffd60a', '#ff2e63'], node: '#ffffff', glow: 0.55 },
  light: { tile: ['#ffffff', '#e4e6ef'], wire: ['#ff8a00', '#ff2e63'], node: '#ffd60a', glow: 0.35 },
} satisfies Record<string, Variant>

// The ring: radius, and the arc it covers, counter-clockwise from the upper
// end of the gap to the lower one.
const RADIUS = 262
const START = 38
const SPAN = 284

const parse = (hex: string): Rgb => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)) as Rgb
const format = (rgb: Rgb) => '#' + rgb.map((v) => Math.round(v).toString(16).padStart(2, '0')).join('')

function colourAt(t: number): string {
  const x = Math.min(0.9999, Math.max(0, t)) * (SPECTRUM.length - 1)
  const i = Math.floor(x)
  const [a, b] = [parse(SPECTRUM[i]), parse(SPECTRUM[i + 1])]
  return format(a.map((v, k) => v + (b[k] - v) * (x - i)) as Rgb)
}

function point(degrees: number): string {
  const r = (degrees * Math.PI) / 180
  return `${(512 + RADIUS * Math.cos(r)).toFixed(1)} ${(512 - RADIUS * Math.sin(r)).toFixed(1)}`
}

function ring(width: number, segments: number): string {
  let out = ''
  for (let i = 0; i < segments; i++) {
    const from = START + (SPAN * i) / segments
    // Each segment overlaps the next slightly, or anti-aliasing shows seams.
    const to = START + (SPAN * (i + 1)) / segments + (i < segments - 1 ? 0.8 : 0)
    out += `<path d="M${point(from)} A${RADIUS} ${RADIUS} 0 0 0 ${point(to)}" stroke="${colourAt((i + 0.5) / segments)}" stroke-width="${width}"/>`
  }
  // Round ends, in the first and last colours.
  const [sx, sy] = point(START).split(' ')
  const [ex, ey] = point(START + SPAN).split(' ')
  out += `<circle cx="${sx}" cy="${sy}" r="${width / 2}" fill="${SPECTRUM[0]}"/>`
  out += `<circle cx="${ex}" cy="${ey}" r="${width / 2}" fill="${SPECTRUM.at(-1)}"/>`
  return `<g fill="none">${out}</g>`
}

function logo(v: Variant): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Generated by scripts/generate-logo.ts - edit that, not this. -->
  <defs>
    <linearGradient id="tile" x1="0" y1="0" x2="1024" y2="1024" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="${v.tile[0]}"/><stop offset="1" stop-color="${v.tile[1]}"/>
    </linearGradient>
    <linearGradient id="wire" x1="512" y1="0" x2="836" y2="0" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="${v.wire[0]}"/><stop offset="1" stop-color="${v.wire[1]}"/>
    </linearGradient>
    <filter id="glow" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="34"/></filter>
    <clipPath id="clip"><rect width="1024" height="1024" rx="228"/></clipPath>
  </defs>
  <rect width="1024" height="1024" rx="228" fill="url(#tile)"/>
  <g clip-path="url(#clip)">
    <g filter="url(#glow)" opacity="${v.glow}">
      ${ring(120, 30)}
      <path d="M512 512 H836" stroke="url(#wire)" stroke-width="100" stroke-linecap="round"/>
    </g>
  </g>
  ${ring(104, 90)}
  <path d="M512 512 H836" stroke="url(#wire)" stroke-width="88" stroke-linecap="round"/>
  <circle cx="512" cy="512" r="80" fill="${v.node}"/>
</svg>
`
}

const dark = logo(VARIANTS.dark)
const light = logo(VARIANTS.light)

writeFileSync(join(root, 'src-tauri/app-icon.svg'), dark)
writeFileSync(join(root, 'src-tauri/app-icon-light.svg'), light)
writeFileSync(join(root, 'public/logo-dark.svg'), dark)
writeFileSync(join(root, 'public/logo-light.svg'), light)
writeFileSync(join(root, 'public/favicon.svg'), dark)
